import re

s = input().strip()
pattern = r'^[A-Za-z].*[0-9]$' #^ -Жолдың басын білдіреді       
#.* -Ортасында кез келген таңбалар (нөл немесе одан да көп) болуы мүмкін
#[0-9] -Жолдың соңғы таңбасы міндетті түрде цифр болуы керек.
#$  - Жолдың соңын білдіреді.
if re.match(pattern, s):
    print("Yes")
else:
    print("No")
