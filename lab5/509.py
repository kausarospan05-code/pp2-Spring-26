import re

s = input().strip()
pattern = r'\b\w{3}\b'
#бұл үзінді сөздің бір бөлігі емес, толық сөз болуы куерек
#\w{3}: \w — кез келген әріп немесе цифр , {3} — оның дәл үш рет қайталануын талап етеді.
#\b: Сөздің соңғы шекарасы

matches = re.findall(pattern, s)#функциясы осы үлгіге сәйкес келетін барлық сөздерді тізімге жинайды
print(len(matches))
