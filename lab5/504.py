import re

s = input().strip() #мәтін қабылдайды және басындағы/соңындағы артық бос орындарды алып тастайды.
digits = re.findall(r'\d', s)#kez kelgen (digit) sign 
print(" ".join(digits))#арасына бос орын қойып, біріктіріп басып шығарады.

#r'\d' үлгісімен 3, 1, 2 жеке цифрлар.
#r'\d+' үлгісімен 3 және 12 бүтін сандар