import re
text = input().strip()
pattern = re.compile(r"^\d+$") 
#^: Мәтіннің басын білдіреді.
#\d: Кез келген цифр (0-9).
#+: Алдыңғы элементтің (яғни цифрдың) бір немесе бірнеше рет қайталануын талап етеді.
#$: Мәтіннің соңын білдіреді.
if pattern.fullmatch(text):#Егер мәтінде сандардан басқа таңба (мысалы, әріп немесе бос орын) болса "No match" нәтижесін береді.
    print("Match")
else:
    print("No match")
